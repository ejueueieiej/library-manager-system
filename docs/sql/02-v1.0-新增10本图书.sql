-- -------------------------------------------------------------
--  自检：执行完看一眼各分类各有多少本
-- -------------------------------------------------------------
SELECT c.name AS 分类, COUNT(*) AS 本数, SUM(b.total_num) AS 总册数
FROM book b
         LEFT JOIN book_category c ON b.category_id = c.id
GROUP BY c.id, c.name
ORDER BY c.id;

-- 自检 2：确认 available_num 和 total_num 一致（新书不该有借出的）
SELECT COUNT(*) AS 可用数与总数不一致的行数
FROM book
WHERE available_num <> total_num;
